#!/usr/bin/env python3
"""
Generate PHASE_TASK_REGISTRY.md from implementation-backlog.yaml (SSOT)
This ensures registry stays synchronized with the canonical backlog.
"""
import yaml
from pathlib import Path

BACKLOG_PATH = Path(__file__).parent.parent.parent / "gptdoc/ANovel_V2_Implementation_Plan_v1.0/implementation-backlog.yaml"
OUTPUT_PATH = Path(__file__).parent / "PHASE_TASK_REGISTRY.md"

PHASE_NAMES = {
    "P0": "Repository & Governance",
    "P1": "Narrative Kernel",
    "P2": "Canon Kernel",
    "P3": "Genre Kernel",
    "P4": "Planning & Contracts",
    "P5": "Context & Model Gateway",
    "P6": "Single-Chapter Production",
    "P7": "Quality & Repair",
    "P8": "Dual-Genre 10-Chapter Certification",
    "P9": "30-Chapter Certification",
    "P10": "Genesis & Reference Intelligence",
    "P11": "Human Calibration & Learning",
    "P12": "100-Chapter Reliability",
    "P13": "Reader / Market Feedback",
    "P14": "300+ Chapter Evolution",
}

def main():
    with open(BACKLOG_PATH) as f:
        backlog = yaml.safe_load(f)

    tasks = backlog["tasks"]

    # Group by phase
    by_phase = {}
    for task in tasks:
        phase = task["phase"]
        if phase not in by_phase:
            by_phase[phase] = []
        by_phase[phase].append(task)

    # Generate markdown
    lines = [
        "# ANovel V2 Phase & Task Registry (SSOT)",
        "",
        "**Document ID**: REGISTRY-0001",
        "**Version**: 2.0 (auto-generated from backlog)",
        "**Status**: NORMATIVE",
        "**Authority**: CONTROL-PLANE-BASELINE",
        "**Source**: `gptdoc/ANovel_V2_Implementation_Plan_v1.0/implementation-backlog.yaml`",
        "**Purpose**: Single source of truth for Phase and Task identity",
        "",
        "---",
        "",
        "## 0. Authority Declaration",
        "",
        "This document is **AUTO-GENERATED** from `implementation-backlog.yaml` (the canonical SSOT).",
        "",
        "**DO NOT EDIT THIS FILE MANUALLY.** Run `task-registry-generator.py` to regenerate.",
        "",
        "---",
        "",
        "## 1. Task Registry by Phase",
        "",
    ]

    for phase in sorted(by_phase.keys()):
        phase_name = PHASE_NAMES.get(phase, phase)
        tasks_in_phase = by_phase[phase]

        lines.append(f"### {phase} — {phase_name}")
        lines.append("")
        lines.append("| Task ID | Title | Goal |")
        lines.append("|---------|-------|------|")

        for task in tasks_in_phase:
            task_id = task["task_id"]
            title = task["title"]
            goal = task["goal"]
            lines.append(f"| **{task_id}** | {title} | {goal} |")

        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## 2. Validation")
    lines.append("")
    lines.append(f"**Total Tasks**: {len(tasks)}")
    lines.append(f"**Phases Covered**: {', '.join(sorted(by_phase.keys()))}")
    lines.append("")
    lines.append("**Generated**: Auto-generated from implementation-backlog.yaml")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("END OF PHASE & TASK REGISTRY")

    with open(OUTPUT_PATH, "w") as f:
        f.write("\n".join(lines))

    print(f"✅ Generated {OUTPUT_PATH}")
    print(f"   {len(tasks)} tasks across {len(by_phase)} phases")

if __name__ == "__main__":
    main()
